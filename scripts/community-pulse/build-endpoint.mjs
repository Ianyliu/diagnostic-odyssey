import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import { build } from "esbuild";

const repo = fileURLToPath(new URL("../../", import.meta.url));
const routes = [
  ["previewEndpoint.ts", "community-pulse.js"],
  ["stagingEndpoint.ts", "community-pulse-staging.js"]
];

for (const [source, name] of routes) {
  const endpoint = new URL("../../apps/web/api/" + name, import.meta.url);
  const [file] = (await build({
    absWorkingDir: repo,
    entryPoints: ["apps/web/src/server/community-pulse/" + source],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node22",
    legalComments: "none",
    banner: { js: "/* eslint-disable */\n// Generated by scripts/community-pulse/build-endpoint.mjs. Edit the server sources." },
    write: false
  })).outputFiles;
  if (!file) throw new Error("Endpoint bundler emitted no file for " + name);
  if (process.argv.includes("--check")) {
    if ((await readFile(endpoint, "utf8")) !== file.text) throw new Error(name + " is out of date.");
  } else {
    await writeFile(endpoint, file.text, "utf8");
  }
}
