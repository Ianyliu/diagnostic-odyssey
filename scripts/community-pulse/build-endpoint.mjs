import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import { build } from "esbuild";

const repo = fileURLToPath(new URL("../../", import.meta.url));
const endpoint = new URL("../../apps/web/api/community-pulse.js", import.meta.url);
const [file] = (await build({
  absWorkingDir: repo,
  entryPoints: ["apps/web/src/server/community-pulse/previewEndpoint.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  legalComments: "none",
  banner: { js: "/* eslint-disable */\n// Generated by scripts/community-pulse/build-endpoint.mjs. Edit the server sources." },
  write: false
})).outputFiles;
if (!file) throw new Error("Preview endpoint bundler emitted no file.");

if (process.argv.includes("--check")) {
  if ((await readFile(endpoint, "utf8")) !== file.text) throw new Error("Community Pulse preview endpoint is out of date.");
} else {
  await writeFile(endpoint, file.text, "utf8");
}
